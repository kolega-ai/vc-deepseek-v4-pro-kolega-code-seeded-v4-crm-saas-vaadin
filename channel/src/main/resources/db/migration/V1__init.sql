-- crm_channel schema: the channel tier's system of record for CRM domain data.
-- Identity is mirrored from the decision tier (which owns it); authorization
-- verdicts are obtained from the decision tier on every request.

create table plans (
    id                      bigint generated by default as identity primary key,
    code                    varchar(20) not null unique,
    name                    varchar(60) not null,
    base_monthly_price      numeric(19,2) not null,
    per_seat_monthly_price  numeric(19,2) not null,
    seats_included          int not null,
    description             varchar(500) not null,
    features                varchar(800) not null,
    sort_order              int not null,
    active                  boolean not null default true
);

create table organizations (
    id               bigint generated by default as identity primary key,
    name             varchar(160) not null,
    plan_id          bigint not null references plans (id),
    status           varchar(20) not null,
    owner_user_id    bigint,
    renewal_date     date,
    billing_contact_id bigint,
    health_score     int not null default 70,
    health_rationale varchar(1000),
    industry         varchar(80),
    country          varchar(80),
    employee_count   int,
    seats            int not null default 10,
    website          varchar(255),
    internal_notes   varchar(4000),
    created_at       timestamp not null,
    updated_at       timestamp not null
);

create index idx_org_status on organizations (status);
create index idx_org_plan on organizations (plan_id);

create table user_accounts (
    id               bigint primary key,
    username         varchar(120) not null unique,
    display_name     varchar(200) not null,
    email            varchar(255) not null unique,
    role             varchar(40) not null,
    enabled          boolean not null default true,
    customer_org_id  bigint,
    title            varchar(120),
    phone            varchar(40),
    created_at       timestamp not null,
    updated_at       timestamp not null
);

create table org_assignments (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    org_id     bigint not null,
    relation   varchar(20) not null,
    constraint uq_channel_assignment unique (user_id, org_id)
);

create index idx_assignment_channel_org on org_assignments (org_id);

create table contacts (
    id            bigint generated by default as identity primary key,
    org_id        bigint not null references organizations (id),
    first_name    varchar(80) not null,
    last_name     varchar(80) not null,
    email         varchar(255) not null,
    phone         varchar(40),
    title         varchar(120),
    permissions   varchar(300),
    is_billing    boolean not null default false,
    is_primary    boolean not null default false,
    user_id       bigint,
    created_at    timestamp not null,
    updated_at    timestamp not null
);

create index idx_contact_org on contacts (org_id);

create table deals (
    id            bigint generated by default as identity primary key,
    org_id        bigint not null references organizations (id),
    name          varchar(160) not null,
    deal_type     varchar(20) not null,
    stage         varchar(30) not null,
    amount        numeric(19,2) not null,
    currency      varchar(3) not null default 'USD',
    probability   int not null,
    close_date    date,
    notes         varchar(2000),
    owner_user_id bigint,
    created_at    timestamp not null,
    updated_at    timestamp not null
);

create index idx_deal_org on deals (org_id);
create index idx_deal_stage on deals (stage);

create table escalations (
    id           bigint generated by default as identity primary key,
    org_id       bigint not null references organizations (id),
    subject      varchar(200) not null,
    description  varchar(4000) not null,
    severity     varchar(10) not null,
    status       varchar(30) not null,
    assignee_id  bigint,
    created_by   bigint,
    created_at   timestamp not null,
    updated_at   timestamp not null,
    resolved_at  timestamp,
    closed_at    timestamp,
    sla_due_at   timestamp,
    sla_breached boolean not null default false
);

create index idx_escalation_status on escalations (status);
create index idx_escalation_assignee on escalations (assignee_id);
create index idx_escalation_org on escalations (org_id);

create table escalation_comments (
    id            bigint generated by default as identity primary key,
    escalation_id bigint not null references escalations (id),
    author_id     bigint,
    author_role   varchar(40),
    visibility    varchar(20) not null,
    body          varchar(4000) not null,
    created_at    timestamp not null
);

create index idx_comment_escalation on escalation_comments (escalation_id);

create table documents (
    id            bigint generated by default as identity primary key,
    org_id        bigint not null references organizations (id),
    name          varchar(255) not null,
    stored_name   varchar(255) not null,
    category      varchar(30) not null,
    visibility    varchar(20) not null,
    content_type  varchar(120) not null,
    size_bytes    bigint not null,
    description   varchar(500),
    uploaded_by   bigint,
    uploaded_at   timestamp not null
);

create index idx_document_org on documents (org_id);

create table api_keys (
    id              bigint generated by default as identity primary key,
    org_id          bigint not null references organizations (id),
    name            varchar(120) not null,
    key_hash        varchar(64) not null unique,
    key_prefix      varchar(12) not null,
    key_last4       varchar(4) not null,
    status          varchar(20) not null,
    created_at      timestamp not null,
    expires_at      timestamp,
    last_used_at    timestamp,
    last_used_path  varchar(120),
    created_by      bigint,
    revoked_at      timestamp,
    rotated_from_id bigint
);

create index idx_api_key_org on api_keys (org_id);

create table webhook_configs (
    id          bigint generated by default as identity primary key,
    org_id      bigint not null references organizations (id),
    url         varchar(500) not null,
    description varchar(200),
    events      varchar(500) not null,
    secret      varchar(200) not null,
    status      varchar(20) not null,
    created_at  timestamp not null,
    updated_at  timestamp not null
);

create index idx_webhook_org on webhook_configs (org_id);

create table webhook_deliveries (
    id               bigint generated by default as identity primary key,
    config_id        bigint not null,
    org_id           bigint not null,
    event_type       varchar(60) not null,
    url              varchar(500) not null,
    status           varchar(20) not null,
    attempt          int not null default 0,
    request_body     text,
    response_status  int,
    response_summary varchar(500),
    error_message    varchar(500),
    created_at       timestamp not null,
    completed_at     timestamp
);

create index idx_delivery_status on webhook_deliveries (status);
create index idx_delivery_config on webhook_deliveries (config_id);

create table notifications (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    type       varchar(40) not null,
    title      varchar(200) not null,
    message    varchar(1000) not null,
    link       varchar(300),
    read_at    timestamp,
    created_at timestamp not null
);

create index idx_notification_user on notifications (user_id, read_at);

-- Append-only audit trail. There is no update or delete path for this table
-- anywhere in the application; every privileged action and every state
-- transition records one row here with the decision-tier authorization basis.
create table audit_events (
    id                   bigint generated by default as identity primary key,
    occurred_at          timestamp not null,
    actor_id             bigint,
    actor_username       varchar(120),
    actor_role           varchar(40),
    action               varchar(80) not null,
    target_type          varchar(60),
    target_id            varchar(80),
    org_id               bigint,
    before_json          text,
    after_json           text,
    authorization_basis  varchar(300) not null,
    customer_visible     boolean not null default false,
    ip_address           varchar(60)
);

create index idx_audit_time on audit_events (occurred_at);
create index idx_audit_org on audit_events (org_id);
create index idx_audit_action on audit_events (action);

create table email_outbox (
    id           bigint generated by default as identity primary key,
    to_address   varchar(255) not null,
    to_user_id   bigint,
    subject      varchar(200) not null,
    body         text not null,
    template     varchar(60) not null,
    status       varchar(20) not null,
    created_at   timestamp not null,
    sent_at      timestamp,
    error_message varchar(500)
);

create index idx_outbox_status on email_outbox (status);

create table password_reset_tokens (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    token_hash varchar(64) not null unique,
    expires_at timestamp not null,
    used_at    timestamp,
    created_at timestamp not null
);

create table invite_tokens (
    id         bigint generated by default as identity primary key,
    email      varchar(255) not null,
    org_id     bigint not null,
    user_id    bigint,
    token_hash varchar(64) not null unique,
    expires_at timestamp not null,
    used_at    timestamp,
    invited_by bigint,
    created_at timestamp not null
);

create table seed_markers (
    marker_key varchar(80) primary key,
    marker_value varchar(200) not null
);
