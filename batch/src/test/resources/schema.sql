create table user_accounts (
    id           bigint primary key,
    username     varchar(120) not null,
    display_name varchar(200) not null,
    email        varchar(255) not null,
    role         varchar(40) not null,
    enabled      boolean not null,
    customer_org_id bigint,
    title        varchar(120),
    phone        varchar(40),
    created_at   timestamp not null,
    updated_at   timestamp not null
);

create table escalations (
    id           bigint generated by default as identity primary key,
    org_id       bigint not null,
    subject      varchar(200) not null,
    description  varchar(4000) not null,
    severity     varchar(10) not null,
    status       varchar(30) not null,
    assignee_id  bigint,
    created_by   bigint,
    created_at   timestamp not null,
    updated_at   timestamp not null,
    resolved_at  timestamp,
    closed_at    timestamp,
    sla_due_at   timestamp,
    sla_breached boolean not null
);

create table notifications (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    type       varchar(40) not null,
    title      varchar(200) not null,
    message    varchar(1000) not null,
    link       varchar(300),
    read_at    timestamp,
    created_at timestamp not null
);

create table audit_events (
    id                   bigint generated by default as identity primary key,
    occurred_at          timestamp not null,
    actor_id             bigint,
    actor_username       varchar(120),
    actor_role           varchar(40),
    action               varchar(80) not null,
    target_type          varchar(60),
    target_id            varchar(80),
    org_id               bigint,
    before_json          text,
    after_json           text,
    authorization_basis  varchar(300) not null,
    customer_visible     boolean not null,
    ip_address           varchar(60)
);

create table api_keys (
    id              bigint generated by default as identity primary key,
    org_id          bigint not null,
    name            varchar(120) not null,
    key_hash        varchar(64) not null,
    key_prefix      varchar(12) not null,
    key_last4       varchar(4) not null,
    status          varchar(20) not null,
    created_at      timestamp not null,
    expires_at      timestamp,
    last_used_at    timestamp,
    last_used_path  varchar(120),
    created_by      bigint,
    revoked_at      timestamp,
    rotated_from_id bigint
);

create table email_outbox (
    id           bigint generated by default as identity primary key,
    to_address   varchar(255) not null,
    to_user_id   bigint,
    subject      varchar(200) not null,
    body         text not null,
    template     varchar(60) not null,
    status       varchar(20) not null,
    created_at   timestamp not null,
    sent_at      timestamp,
    error_message varchar(500)
);

create table webhook_configs (
    id          bigint generated by default as identity primary key,
    org_id      bigint not null,
    url         varchar(500) not null,
    description varchar(200),
    events      varchar(500) not null,
    secret      varchar(200) not null,
    status      varchar(20) not null,
    created_at  timestamp not null,
    updated_at  timestamp not null
);

create table webhook_deliveries (
    id               bigint generated by default as identity primary key,
    config_id        bigint not null,
    org_id           bigint not null,
    event_type       varchar(60) not null,
    url              varchar(500) not null,
    status           varchar(20) not null,
    attempt          int not null,
    request_body     text,
    response_status  int,
    response_summary varchar(500),
    error_message    varchar(500),
    created_at       timestamp not null,
    completed_at     timestamp
);

create table organizations (
    id               bigint primary key,
    name             varchar(160) not null,
    plan_id          bigint not null,
    status           varchar(20) not null,
    owner_user_id    bigint,
    renewal_date     date,
    billing_contact_id bigint,
    health_score     int not null,
    health_rationale varchar(1000),
    industry         varchar(80),
    country          varchar(80),
    employee_count   int,
    seats            int not null,
    website          varchar(255),
    internal_notes   varchar(4000),
    created_at       timestamp not null,
    updated_at       timestamp not null
);
