-- crm_decision schema: identity, organization assignments and API-key records.
-- This database is the AUTHORITATIVE source for role, scope and limits.
-- The channel tier never reads from it directly; it asks this service.

create table auth_users (
    id              bigint primary key,
    username        varchar(120) not null unique,
    display_name    varchar(200) not null,
    email           varchar(255) not null unique,
    role            varchar(40) not null,
    enabled         boolean not null default true,
    customer_org_id bigint,
    password_hash   varchar(100) not null,
    created_at      timestamp not null,
    updated_at      timestamp not null
);

create table org_assignments (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    org_id     bigint not null,
    relation   varchar(20) not null,
    constraint uq_assignment unique (user_id, org_id)
);

create index idx_assignment_org on org_assignments (org_id);

-- API-key records are synced from the channel tier (the key issuer). Only the
-- SHA-256 hash of the key is ever stored or transported; the secret itself
-- never leaves the channel tier and is shown exactly once at creation time.
create table api_key_records (
    key_hash   varchar(64) primary key,
    org_id     bigint not null,
    name       varchar(120) not null,
    status     varchar(20) not null,
    expires_at timestamp
);

create index idx_api_key_org on api_key_records (org_id);

-- Append-only record of every authorization decision. No update or delete
-- endpoint exists for this table.
create table authz_events (
    id          bigint generated by default as identity primary key,
    occurred_at timestamp not null,
    user_id     bigint,
    username    varchar(120),
    role        varchar(40),
    principal   varchar(40),
    action      varchar(80) not null,
    org_id      bigint,
    allowed     boolean not null,
    basis       varchar(300) not null
);

create index idx_authz_time on authz_events (occurred_at);
