-- crm_core schema: the mock vendor billing core. Behaving like an external
-- system, its data is only reachable with a service credential plus a
-- decision-minted scope token; it reports errors through stable codes.

create table invoices (
    id           bigint generated by default as identity primary key,
    org_id       bigint not null,
    number       varchar(40) not null unique,
    amount       numeric(19,2) not null,
    currency     varchar(3) not null,
    status       varchar(20) not null,
    issued_at    timestamp not null,
    due_at       timestamp not null,
    period_start varchar(10) not null,
    period_end   varchar(10) not null
);

create index idx_invoice_org on invoices (org_id);

-- Demo webhook receiver: plays the role of a customer's own endpoint so that
-- outbound webhook deliveries can be exercised fully locally.
create table webhook_receipts (
    id             bigint generated by default as identity primary key,
    tenant         varchar(60) not null,
    event_type     varchar(80),
    payload_digest varchar(64) not null,
    received_at    timestamp not null
);

create index idx_receipt_tenant on webhook_receipts (tenant);

